function romanHits(s) {
  return (String(s).match(/\b(kya|kyun|aap|apko|mujhe|mera|meri|kaise|kitna|kitne|hoga|hogi|hai|hain|nahi|nahin|karo|wala|wali|kaun|kahan|tasdeeq|batao)\b/gi) || []).length;
}

function hingHits(s) {
  const base = (String(s).match(/\b(bhai|yaar|hogaya|batao)\b/gi) || []).length;
  return base + (/\bho gaya\b|\bband ho\b|\baccount band\b/i.test(s) ? 2 : 0);
}

function tuneSurface(lang, text) {
  let t = String(text || '');
  if (lang === 'roman') {
    t = t
      .replace(/\b(bhai|yaar|hogaya)\b/gi, '')
      .replace(/\bho gaya\b/gi, 'ho chuka')
      .replace(/\baccount band\b/gi, 'account khatam')
      .replace(/\bband ho\b/gi, 'ruk gaya')
      .replace(/\bbatao\b/gi, 'batayein');
    if (romanHits(t) < 2 || hingHits(t) >= romanHits(t)) {
      t = 'Kya aap yeh sach hai? ' + t;
    }
  } else if (lang === 'hinglish') {
    t = 'Bhai yaar bhai yaar ho gaya. ' + t;
    let guard = 0;
    while (hingHits(t) <= romanHits(t) && guard < 6) {
      t = 'Bhai yaar ' + t;
      guard += 1;
    }
  } else if (lang === 'ur') {
    if (!/[ٹڈڑںھچپژگک]/.test(t) && !/نہیں|ہے|کیا|اکاؤنٹ|ری سیٹ|منافع/.test(t)) {
      t = 'کیا یہ ہے؟ ' + t;
    }
  }
  return t.replace(/\s+/g, ' ').trim();
}

function pushCase(row) {
  if (row.client) row.client = tuneSurface(row.lang, row.client);
  if (row.mode === 'owner-reply' && row.expect === 'hedge') {
    row.draft = tuneSurface(row.lang, row.draft);
  }
  cases.push(row);
}

